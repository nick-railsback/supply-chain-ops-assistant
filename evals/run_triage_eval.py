"""Reference triage-eval runner behind `make eval-triage`.

Classifies each stuck-order case in `evals/triage_dataset.jsonl` through a
single forced-tool-use Claude call (`agent.llm.structured_call`, imported
unmodified), scores the result against the case's own gold `label`, and
reports the resulting accuracy. A `--min-accuracy` floor turns the report
into a gate; without one, accuracy is reported but never gates the exit code.

Stays out of `suite_cmd` and CI: a live Claude call is nondeterministic and
costs tokens, so nothing here is asserted by an automated threshold —
`tests/test_triage_eval_runner.py` covers the offline plumbing (gold-set
wiring, call shape, report format, gate logic) against a faked client.
"""

from __future__ import annotations

import argparse
import asyncio
import json
from pathlib import Path

from rich.console import Console

from agent.llm import structured_call
from triage.taxonomy import RootCause

DATASET = Path(__file__).parent / "triage_dataset.jsonl"
REPORT = Path(__file__).parent / "TRIAGE_REPORT.md"
console = Console()

TRIAGE_TOOL_NAME = "emit_root_cause"
TRIAGE_TOOL_DESCRIPTION = "Classify the stuck order's root cause from the evidence provided."
TRIAGE_TOOL_SCHEMA: dict = {
    "type": "object",
    "properties": {
        "root_cause": {"type": "string", "enum": [rc.value for rc in RootCause]},
        "reasoning": {
            "type": "string",
            "description": "one sentence: the evidence that supports this",
        },
    },
    "required": ["root_cause", "reasoning"],
}

SYSTEM_PROMPT = f"""You are a supply-chain operations analyst triaging a stuck order.

A "stuck" order has failed to progress through fulfillment as expected.
Every stuck order has exactly one root cause, drawn from this closed
taxonomy:

- {RootCause.INVENTORY.value}: the order cannot be fulfilled because of an
  inventory shortfall — insufficient quantity on hand, or allocated stock
  exceeding what is available, for one or more of the order's SKUs.
- {RootCause.CARRIER.value}: the order shipped, but the carrier has failed
  to move it as promised — an SLA breach, a stalled tracking event, or a
  flagged shipment.
- {RootCause.ADDRESS_EXCEPTION.value}: the order cannot be delivered because
  of a problem with the destination itself — an invalid, incomplete, or
  undeliverable address.

You are given the order, its line items, any recorded exceptions, its
shipment, and current inventory levels for its SKUs, all as of a point in
time. Classify the single root cause that best explains why the order is
stuck, and give one sentence of supporting reasoning.
"""


def _build_user_prompt(case: dict) -> str:
    # Deliberately keyed off an explicit allow-list, never `case.keys()` --
    # a case-shaped dict growing a new top-level field later must not
    # silently start leaking it into the prompt. `label` is never read here.
    fields = {
        k: case[k]
        for k in (
            "case_id",
            "as_of",
            "order",
            "line_items",
            "exceptions",
            "shipment",
            "inventory",
        )
        if k in case
    }
    return json.dumps(fields, indent=2, default=str)


async def _classify_case(case: dict) -> tuple[str, str]:
    user = _build_user_prompt(case)
    data, _usage = await structured_call(
        system=SYSTEM_PROMPT,
        user=user,
        tool_name=TRIAGE_TOOL_NAME,
        tool_description=TRIAGE_TOOL_DESCRIPTION,
        input_schema=TRIAGE_TOOL_SCHEMA,
    )
    return data["root_cause"], data.get("reasoning", "")


def classify_case(case: dict) -> tuple[str, str]:
    return asyncio.run(_classify_case(case))


def _write_report(dataset_size: int, correct: int, accuracy: float, misses: list[str]) -> None:
    lines = [
        "# Triage Eval Report",
        "",
        "_Generated by `make eval-triage`. Numbers are measured, not asserted._",
        "",
        f"- Accuracy: **{correct}/{dataset_size} ({accuracy:.0%})**",
        "",
    ]
    if misses:
        lines.append("## Misses")
        lines.append("")
        lines.extend(f"- {m}" for m in misses)
        lines.append("")
    REPORT.write_text("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser(description="Triage root-cause reference eval")
    ap.add_argument("--dataset", type=Path, default=DATASET)
    ap.add_argument("--min-accuracy", type=float, default=None)
    ap.add_argument("--verbose", action="store_true", help="print per-case misses")
    args = ap.parse_args()

    dataset = [json.loads(line) for line in args.dataset.read_text().splitlines() if line.strip()]

    correct = 0
    misses: list[str] = []
    for case in dataset:
        predicted, _reasoning = classify_case(case)
        if predicted == case["label"]:
            correct += 1
        else:
            misses.append(f"{case['case_id']}: predicted={predicted} actual={case['label']}")

    accuracy = correct / len(dataset) if dataset else 0.0
    console.print(f"Triage accuracy: {correct}/{len(dataset)} ({accuracy:.0%})")
    if args.verbose:
        for m in misses:
            console.print(f"  [red]✗[/red] {m}")

    _write_report(len(dataset), correct, accuracy, misses)
    console.print(f"[dim]Report written to {REPORT}[/dim]")

    if args.min_accuracy is not None and accuracy < args.min_accuracy:
        console.print(
            f"[red]threshold not met:[/red] accuracy {accuracy:.1%} "
            f"< required {args.min_accuracy:.1%}"
        )
        raise SystemExit(1)


if __name__ == "__main__":
    main()
